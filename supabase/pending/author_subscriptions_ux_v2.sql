create or replace function public.get_subscription_feed_candidates(
  p_source text default 'all',
  p_content_kind text default null,
  p_published_before timestamptz default null,
  p_id_before uuid default null,
  p_limit integer default 30
)
returns table (
  post_id uuid,
  matched_author_ids uuid[],
  matched_topic_keys text[],
  published_at timestamptz
)
language sql
security definer
set search_path = public
as $$
  with candidate as (
    select
      p.id as post_id,
      p.published_at,
      array(
        select distinct matched.author_id
        from (
          select s.author_id
          from public.author_subscriptions s
          where s.subscriber_id = auth.uid() and s.author_id = p.author_id
          union
          select s.author_id
          from public.author_subscriptions s
          join public.post_authors pa
            on pa.user_id = s.author_id
           and pa.post_id = p.id
           and pa.accepted_at is not null
          where s.subscriber_id = auth.uid()
        ) matched
      ) as matched_author_ids,
      array(
        select ts.topic_key
        from public.topic_subscriptions ts
        where ts.subscriber_id = auth.uid()
          and ts.topic_key = any(coalesce(p.topic_keys, '{}'::text[]))
      ) as matched_topic_keys
    from public.posts p
    where auth.uid() is not null
      and p.status = 'published'
      and (p_content_kind is null or p.content_kind = p_content_kind)
      and p.author_id <> auth.uid()
      and not exists (
        select 1 from public.post_authors own_credit
        where own_credit.post_id = p.id
          and own_credit.user_id = auth.uid()
          and own_credit.accepted_at is not null
      )
      and not exists (
        select 1 from public.user_blocks b
        where (b.blocker_id = auth.uid() and b.blocked_id = p.author_id)
           or (b.blocker_id = p.author_id and b.blocked_id = auth.uid())
      )
      and (
        p_published_before is null
        or (p.published_at, p.id) < (p_published_before, p_id_before)
      )
  )
  select c.post_id, c.matched_author_ids, c.matched_topic_keys, c.published_at
  from candidate c
  where p_source in ('all', 'authors', 'topics')
    and (
      (p_source in ('all', 'authors') and cardinality(c.matched_author_ids) > 0)
      or
      (p_source in ('all', 'topics') and cardinality(c.matched_topic_keys) > 0)
    )
  order by c.published_at desc, c.post_id desc
  limit least(greatest(p_limit, 1), 30);
$$;

revoke all on function public.get_subscription_feed_candidates(
  text, text, timestamptz, uuid, integer
) from public, anon;
grant execute on function public.get_subscription_feed_candidates(
  text, text, timestamptz, uuid, integer
) to authenticated;
